  subtitle,
  enhancement,
  shorts,
  podcast,
  screenDemo,
  localization,
  hybrid,
  characterAnimation,
  footage,
  library,
  threeD,
  aiTools,
  graphicsTools,
}

class FeatureCatalogEntry {
  const FeatureCatalogEntry({
    required this.id,
    required this.title,
    required this.description,
    required this.type,
    required this.category,
    required this.destination,
    this.capabilityId,
    this.workflowId,
    this.pipelineId,
    this.availability = FeatureAvailability.notImplemented,
    required this.icon,
    this.demo = true,
  });
  final String id, title, description;
  final CatalogType type;
  final CatalogCategory category;
  final StudioDestination destination;
  final String? capabilityId, workflowId, pipelineId;
  final FeatureAvailability availability;
  final IconData icon;
  final bool demo;
}

