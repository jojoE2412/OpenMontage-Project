import 'package:flutter/material.dart';

enum CatalogType { capability, workflow, tool, asset }

enum CatalogCategory { generate, edit, production, assets, advanced, workflows }

enum FeatureAvailability {
  available,
  configRequired,
  dependencyMissing,
  unavailable,
  notImplemented,
}

enum StudioDestination {
  aiVideo,
